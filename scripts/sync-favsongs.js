// Rebuilds favsongs-data.js from the Apple Music playlist "Emmy's Favorite".
// Run:  node scripts/sync-favsongs.js
// One CD per album (the songs from the playlist get a heart in the tracklist), sorted by cover colour:
// light/white covers → red → orange → yellow → green → blue → purple → pink → dark/black covers.
const fs = require("fs");
const path = require("path");

const PLAYLIST = "https://music.apple.com/th/playlist/emmys-favorite/pl.u-oZylM7WsG1Jyddv";
const OUT = path.join(__dirname, "..", "favsongs-data.js");

const hsl = (hex) => {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
  if (!d) return { h: 0, s: 0, l };
  const s = d / (1 - Math.abs(2 * l - 1));
  const h = max === r ? ((g - b) / d + 6) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return { h: h * 60, s, l };
};
// 0 = light neutrals, 1 = colours (by hue), 2 = dark neutrals
const colourKey = (hex) => {
  const { h, s, l } = hsl(hex);
  if (l > .9 || (s < .14 && l >= .5)) return [0, -l];
  if (l < .1 || s < .14) return [2, -l];
  return [1, (h + 15) % 360]; // start the rainbow at deep red (hue 345°)
};
const byColour = (a, b) => {
  const [ga, va] = colourKey(a.bg), [gb, vb] = colourKey(b.bg);
  return ga - gb || va - vb;
};

(async () => {
  const html = await (await fetch(PLAYLIST, { headers: { "user-agent": "Mozilla/5.0" } })).text();
  const json = html.match(/<script type="application\/json" id="serialized-server-data">([\s\S]*?)<\/script>/)?.[1];
  if (!json) throw new Error("playlist data not found on the page");

  const tracks = [];
  const walk = (o) => {
    if (!o || typeof o !== "object") return;
    if (o.contentDescriptor?.kind === "song" && o.tertiaryLinks?.[0] && o.artwork) { tracks.push(o); return; }
    Object.values(o).forEach(walk);
  };
  walk(JSON.parse(json));

  const albums = new Map();
  for (const t of tracks) {
    const link = t.tertiaryLinks[0];
    const id = Number(link.segue.destination.contentDescriptor.identifiers.storeAdamID);
    const art = t.artwork.dictionary;
    const songId = Number(t.contentDescriptor.identifiers.storeAdamID);
    if (!albums.has(id)) {
      albums.set(id, {
        id, title: link.title, artist: t.subtitleLinks?.[0]?.title || "",
        cover: art.url.replace("{w}x{h}bb.{f}", "600x600bb.jpg"),
        bg: art.bgColor, fg: art.textColor1, fg2: art.textColor2, fav: [],
      });
    }
    const album = albums.get(id);
    if (!album.fav.some(([fid]) => fid === songId)) album.fav.push([songId, t.title, t.duration || 0]);
  }

  const list = [...albums.values()].sort(byColour);
  const q = JSON.stringify;
  const body = list.map((a) => `  { id: ${a.id}, title: ${q(a.title)}, artist: ${q(a.artist)}, bg: "${a.bg}", fg: "${a.fg}", fg2: "${a.fg2}", fav: ${q(a.fav)}, cover: ${q(a.cover)} },`).join("\n");
  fs.writeFileSync(OUT, `// Generated by scripts/sync-favsongs.js from ${PLAYLIST}
// ${tracks.length} songs · ${list.length} albums · sorted by cover colour. Re-run the script after changing the playlist.
// id: Apple Music album id · bg/fg/fg2: cover colours from Apple Music · fav: songs from the playlist [song id, name, ms]
window.FAV_PLAYLIST = ${q(PLAYLIST)};
window.FAV_ALBUMS = [
${body}
];
`);
  console.log(`${tracks.length} songs → ${list.length} albums → ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => { console.error(e.message); process.exit(1); });
